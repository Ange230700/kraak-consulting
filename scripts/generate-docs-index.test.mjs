function writeMarkdown(root, file, content) {
  const target = path.join(root, file);

  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(
    target,
    content.trimStart().replace(/\n/g, '\n') + '\n',
    'utf8',
  );
}

